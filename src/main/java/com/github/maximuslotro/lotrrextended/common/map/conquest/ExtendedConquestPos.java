package com.github.maximuslotro.lotrrextended.common.map.conquest;

public class ExtendedConquestPos {
	private final int x;
	private final int z;

	public ExtendedConquestPos(int x, int z) {
		this.x = x;
		this.z = z;
	}

	public int getPosX() {
		return x;
	}

	public int getPosZ() {
		return z;
	}
}
