package com.github.maximuslotro.lotrrextended.common.world.gen.structureV5;

/**
 * Enum representing different types of structures used in the mod.
 * <p>
 * Each constant corresponds to a specific thematic or regional structure category.
 */
public enum ExtendedStructureType {
	/** Ranger-themed structures. */
	RANGER, 
	/** Structures associated with Gundabad Orcs. */
	GUNDABAD_ORC, 
	/** Hobbit-themed structures. */
	HOBBIT, 
	/** Ruined structures. */
	RUIN, 
	/** Barrow or burial mound structures. */
	BARROW, 
	/** Small hamlet structures in Bree region. */
	BREE_HAMLET, 
	 /** Larger village structures in Bree region. */
	BREE_VILLAGE, 
	/** Structures themed around the Blue Mountains. */
	BLUE_MOUNTAINS,
	/** Structures that are lore builds. */
	LORE;
}
